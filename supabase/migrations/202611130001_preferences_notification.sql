-- Mode de notification choisi par le boutiquier :
--   webpush = notifications instantanées (comportement historique, par défaut)
--   email   = alertes par e-mail, plan de secours pour les téléphones qui ne
--             supportent pas le Web Push (vieux iPhone, Android sans services
--             Google, navigateurs exotiques).
-- Écriture réservée au serveur : la RLS est active et aucune politique publique
-- n'est créée, seules les Edge Functions (rôle service) écrivent et lisent.
create table if not exists public.preferences_notification (
  id bigint generated by default as identity primary key,
  telephone_boutique text not null unique,
  nom_boutique text,
  mode_notification text not null default 'webpush',
  email_notification text,
  maj_le timestamp with time zone not null default now(),
  constraint preferences_notification_mode_check
    check (mode_notification in ('webpush', 'email'))
);

alter table public.preferences_notification enable row level security;

comment on table public.preferences_notification is
  'Mode de notification du boutiquier (webpush ou email) et adresse e-mail de secours. Écrit par envoyer-inscription, lu par envoyer-commande.';
